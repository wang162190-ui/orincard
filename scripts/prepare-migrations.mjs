import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const developmentProjectRef = "ettuzeunkadkfnawawdy";
const sources = ["identity.sql", "projects.sql", "assets.sql", "jobs-usage.sql", "ai-asset-budget.sql", "deletion.sql", "tool-outputs.sql", "billing.sql"];
const target = resolve(
  root,
  "supabase/migrations/20260906000100_walking_skeleton.sql",
);

function assertDevelopmentProject(environment) {
  const projectRef = environment.SUPABASE_PROJECT_REF?.trim();
  const productionRef = environment.SUPABASE_PRODUCTION_PROJECT_REF?.trim();
  if (projectRef && productionRef && projectRef === productionRef) {
    throw new Error("Migration preparation cannot target the production project.");
  }
  if (projectRef && projectRef !== developmentProjectRef) {
    throw new Error("Migration preparation is restricted to the approved development project.");
  }
}

async function expectedMigration() {
  const sections = await Promise.all(
    sources.map(async (source) => {
      const path = resolve(root, "supabase/definitions", source);
      return `-- source: supabase/definitions/${source}\n${(await readFile(path, "utf8")).trim()}\n`;
    }),
  );
  return [
    "-- Generated by scripts/prepare-migrations.mjs. Do not edit by hand.",
    "-- T016-T019 walking skeleton database baseline.",
    "",
    ...sections,
  ].join("\n");
}

async function main() {
  assertDevelopmentProject(process.env);
  const expected = await expectedMigration();
  if (process.argv.includes("--check")) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== expected) {
      throw new Error("Walking skeleton migration is missing or stale.");
    }
    return;
  }
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, expected);
}

await main();
